test('cadastro, corte, dois atores, transformação, trace e QR usam a API e o banco reais',async({page,context},testInfo)=>{
  test.setTimeout(120_000);
  await page.route(/https:\/\/[^/]*tile\.openstreetmap\.org\//,route=>route.abort());
  await page.goto('/');
  const personasResponse=await page.request.get('/api/v1/auth/personas');expect(personasResponse.ok()).toBeTruthy();
  const personas=(await personasResponse.json()).personas as Array<{id:string;name:string;organization:{id:string}}>;
  const author=personas.find(persona=>persona.name==='Autora entregável')!;
  const receiver=personas.find(persona=>persona.name===(testInfo.project.name==='mobile-chromium'?'Recebedor RS entregável':'Recebedor entregável'))!;
  const destination=testInfo.project.name==='mobile-chromium'?'RS':'SP';
  expect(author).toBeTruthy();expect(receiver).toBeTruthy();
  await page.getByLabel('PERFIL DE DEMONSTRAÇÃO').selectOption(author.id);
  await expect(page.getByRole('button',{name:'Registrar parcela'})).toBeEnabled();
  const unique=`UI-LIVE-${testInfo.project.name}-${Date.now()}`;
  await page.getByLabel('Identificação da propriedade').fill(unique);
  await page.getByRole('button',{name:'Carregar exemplo sintético'}).click();
  await page.getByRole('button',{name:'Registrar parcela'}).click();
  await expect(page.getByText('Parcela persistida; confira os dados em Origem & sinais.')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('01-registration.png'),fullPage:true});
  let dashboard=await (await page.request.get('/api/v1/dashboard')).json();
  const plot=dashboard.plots.find((item:{declared_property:string})=>item.declared_property===unique);expect(plot).toBeTruthy();
  await page.getByRole('button',{name:'Próxima etapa'}).click();
  await page.getByLabel('Parcela vinculada').selectOption(plot.id);
  await page.getByLabel('Código do lote').fill(unique);
  await page.getByLabel('Documento de autorização (privado)').setInputFiles({name:'autorizacao-sintetica.txt',mimeType:'text/plain',buffer:Buffer.from(`AUTORIZAÇÃO FICTÍCIA ${unique} — SEM VALOR OFICIAL`)});
  await page.getByRole('button',{name:'Enviar documento privado'}).click();
  await expect(page.getByText('Documento enviado e mantido privado.')).toBeVisible();
  await page.getByRole('button',{name:'Registrar lote',exact:false}).click();
  await expect(page.getByText('Lote enviado para validação da API.')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('02-origin.png'),fullPage:true});
  dashboard=await (await page.request.get('/api/v1/dashboard')).json();
  const origin=dashboard.origin_lots.find((item:{code:string})=>item.code===unique);expect(origin).toBeTruthy();
  await page.getByRole('button',{name:'Próxima etapa'}).click();
  await page.getByLabel('Lote disponível').selectOption(origin.id);
  await page.getByLabel('Volume de corte (m³)').fill('10');
  await page.getByRole('button',{name:'Registrar corte',exact:false}).click();
  await expect(page.getByText('Solicitação de corte enviada para validação.')).toBeVisible();
  await page.getByLabel('Organização destinatária').selectOption(receiver.organization.id);
  await page.getByLabel('UF de destino').selectOption(destination);
  await expect(page.getByText(`Cobertura normativa AM → ${destination}: PENDENTE DE VERIFICAÇÃO. O registro declaratório não representa autorização nem libera prontidão.`)).toBeVisible();
  await page.getByRole('button',{name:'Criar remessa',exact:true}).click();
  await expect(page.getByText('Solicitação de remessa enviada para validação.')).toBeVisible();
  dashboard=await (await page.request.get('/api/v1/dashboard')).json();
  expect(dashboard.shipments.find((item:{items:Array<{lot_id:string}>})=>item.items.some(line=>line.lot_id===origin.id)).destination_state).toBe(destination);
  await page.getByRole('button',{name:'Confirmar expedição',exact:true}).click();
  await expect(page.getByText('Expedição confirmada pelo remetente.')).toBeVisible();
  await page.getByLabel('PERFIL DE DEMONSTRAÇÃO').selectOption(receiver.id);
  await page.getByRole('button',{name:'Confirmar recebimento',exact:true}).click();
  await expect(page.getByText('Recebimento registrado pelo destinatário; confira divergências R09.')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('03-custody.png'),fullPage:true});
  dashboard=await (await page.request.get('/api/v1/dashboard')).json();
  expect(dashboard.origin_lots.find((item:{id:string})=>item.id===origin.id).available_m3).toBe('10');
  await page.getByRole('button',{name:'Próxima etapa'}).click();
  await page.getByLabel('Identificação da transformação').fill(`${unique}-SERR`);
  const parameter=dashboard.conversion_parameters.find((item:{input_product:string})=>item.input_product==='tora')??dashboard.conversion_parameters[0];
  await page.getByLabel('Parâmetro de conversão').selectOption(parameter.id);
  await page.getByLabel('Lote de entrada').selectOption(origin.id);
  await page.getByRole('button',{name:'Preencher alocação para conferir'}).click();
  await page.getByRole('button',{name:'Registrar transformação',exact:false}).click();
  await expect(page.getByText('Transformação persistida; confira saldo, alocações e checagens.')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('04-transformation.png'),fullPage:true});
  dashboard=await (await page.request.get('/api/v1/dashboard')).json();
  const product=dashboard.product_lots.find((item:{code:string})=>item.code===`${unique}-SERR`);expect(product).toBeTruthy();
  expect(dashboard.origin_lots.find((item:{id:string})=>item.id===origin.id).available_m3).toBe('0');
  await page.getByRole('button',{name:'Próxima etapa'}).click();
  await page.screenshot({path:testInfo.outputPath('05-review.png'),fullPage:true});
  await page.getByRole('button',{name:'Próxima etapa'}).click();
  await page.getByLabel('Produto para rastrear').selectOption(product.id);
  await expect(page.getByText('3 / 3 m³',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Mapa da parcela declarada')).toBeVisible();
  await page.getByLabel('Lote de produto',{exact:false}).selectOption(product.id);
  await page.getByRole('button',{name:'Gerar passaporte',exact:false}).click();
  await expect(page.getByAltText('QR para consulta pública do passaporte')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('live-passport-trace.png'),fullPage:true});
  await page.screenshot({path:testInfo.outputPath('06-passport.png'),fullPage:true});
  const publicLink=page.getByRole('link',{name:'Abrir consulta pública'});
  const publicPagePromise=context.waitForEvent('page');await publicLink.click();const publicPage=await publicPagePromise;
  await publicPage.getByRole('button',{name:'Consultar passaporte'}).click();
  await expect(publicPage.locator('.public-result')).toContainText('MISSING_EVIDENCE');
  await expect(publicPage.getByLabel('Mapa público da região generalizada')).toBeVisible();
  await expect(publicPage.getByText(/-60/)).toHaveCount(0);
  await publicPage.screenshot({path:testInfo.outputPath('08-public.png'),fullPage:true});
  await page.getByRole('button',{name:'Próxima etapa'}).click();
  await page.screenshot({path:testInfo.outputPath('07-bundle.png'),fullPage:true});
  dashboard=await (await page.request.get('/api/v1/dashboard')).json();
  const passport=dashboard.passports.find((item:{product_lot_id:string})=>item.product_lot_id===product.id);
  await page.getByLabel('Passaporte para exportar').selectOption(passport.id);
  for(const format of ['JSON','HTML']) {
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('button',{name:new RegExp(`Baixar ${format}`)}).click();
    const download=await downloadPromise; const file=testInfo.outputPath(`bundle.${format.toLowerCase()}`);await download.saveAs(file);
    expect(await readFile(file,'utf8')).toContain('MISSING_EVIDENCE');
  }
});

test('misturas60/40, origem desconhecida e revisão distinta são recuperadas do banco real',async({page},testInfo)=>{
  test.setTimeout(90_000);await page.route(/https:\/\/[^/]*tile\.openstreetmap\.org\//,route=>route.abort());
  await page.goto('/');
  await page.getByLabel('PERFIL DE DEMONSTRAÇÃO').selectOption('20000000-0000-4000-8000-000000000012');
  await expect(page.getByRole('button',{name:'Registrar parcela'})).toBeEnabled();
  const dashboard=await (await page.request.get('/api/v1/dashboard')).json();
  for(let index=0;index<5;index++)await page.getByRole('button',{name:'Próxima etapa'}).click();
  const known=dashboard.product_lots.find((item:{code:string})=>item.code==='DELIVERY-PRODUCT-2');
  const unknown=dashboard.product_lots.find((item:{code:string})=>item.code==='DELIVERY-PRODUCT-3');
  expect(known).toBeTruthy();expect(unknown).toBeTruthy();
  await page.getByLabel('Produto para rastrear').selectOption(known.id);
  await expect(page.getByRole('cell',{name:'60%',exact:true})).toBeVisible();await expect(page.getByRole('cell',{name:'40%',exact:true})).toBeVisible();
  // The current seed has two origin lots on one declared parcel; show each unique parcel once.
  await expect(page.getByLabel('Mapa da parcela declarada').first()).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('mixture-known-60-40.png'),fullPage:true});
  await page.getByLabel('Produto para rastrear').selectOption(unknown.id);
  await expect(page.getByText('1.8 / 3 m³',{exact:true})).toBeVisible();await expect(page.getByText('1.2 / 3 m³',{exact:true})).toBeVisible();
  await expect(page.getByRole('cell',{name:'Origem desconhecida',exact:true})).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('mixture-unknown-60-40.png'),fullPage:true});
  await page.getByLabel('PERFIL DE DEMONSTRAÇÃO').selectOption('20000000-0000-4000-8000-000000000013');
  await page.getByRole('button',{name:'Etapa anterior'}).click();
  const auditDashboard=await (await page.request.get('/api/v1/dashboard')).json();
  const review=auditDashboard.audit_cases.find((item:{rule_id:string;status:string})=>item.rule_id==='R10'&&['ABERTO','EM_ANALISE','MANTIDO_PENDENTE'].includes(item.status));
  expect(review).toBeTruthy();await page.getByLabel('Caso de revisão').selectOption(review.id);
  await expect(page.getByText(/Resultado efetivo de revisão/)).toBeVisible();
  const reviewComment=`E2E real ${testInfo.project.name} ${Date.now()}: manter pendente; demonstração não substitui evidência competente.`;
  await page.getByLabel('Justificativa da decisão').fill(reviewComment);
  await page.getByRole('button',{name:'Registrar decisão'}).click();
  await expect(page.getByText('Decisão registrada; histórico original e evidências preservados.')).toBeVisible();
  await expect(page.locator('p').filter({hasText:reviewComment})).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('review-distinct-auditor.png'),fullPage:true});
});
