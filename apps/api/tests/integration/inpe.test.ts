import { beforeAll, afterAll, it, expect } from 'vitest';
import { randomUUID } from 'node:crypto';
import { PrismaClient } from '@prisma/client';
import { buildServer } from '../../src/app.js';
import { configureImageryForTests } from '../../src/services/inpe-routes.js';
import { searchInpe } from '../../src/services/inpe.js';
import { sha256Canonical } from '../../src/services/integrity.js';
const owner = new PrismaClient({ datasources: { db: { url: process.env.TEST_DATABASE_URL! } } });
const org = randomUUID(), other = randomUUID(), user = randomUUID(), user2 = randomUUID();
const geometry = { type: 'Polygon' as const, coordinates: [[[-60, -3], [-59.999, -3], [-59.999, -2.999], [-60, -2.999], [-60, -3]]] };
const datetime = '2026-01-01T00:00:00Z/2026-11-01T00:00:00Z';
const asset = (band: string) => `https://data.inpe.br/bdc/data/s2-16d/v2/016/009/2026/10/16/S2-16D_V2_016009_20261016_${band}.tif`;
let app: Awaited<ReturnType<typeof buildServer>>, headers: Record<string, string>, headers2: Record<string, string>, calls = 0, active = true, now = Date.now();
const post = (url: string, payload: unknown, h = headers, key = randomUUID()) => app.inject({ method: 'POST', url, headers: { ...h, 'idempotency-key': key }, payload: payload as object });
beforeAll(async () => {
    await owner.organization.createMany({ data: [org, other].map(id => ({ id, name: 'INPE teste', role: 'OPERATOR', state: 'AM', municipality: 'Sintético', data_provenance: { label: 'SIMULADA' } })) });
    await owner.user.createMany({ data: [{ id: user, organization_id: org, name: 'INPE', roles: ['OPERATOR'] }, { id: user2, organization_id: other, name: 'Outro', roles: ['OPERATOR'] }] });
    await owner.membership.createMany({ data: [{ user_id: user, organization_id: org, role: 'OPERATOR' }, { user_id: user2, organization_id: other, role: 'OPERATOR' }] });
    configureImageryForTests({ enabled: () => active, now: () => now, search: async (input, bbox) => { calls++; return searchInpe(input, bbox, async () => ({ status: 200, body: { features: [{ id: 'synthetic-scene', collection: 'S2-16D-2', geometry, bbox: [-60, -3, -59.999, -2.999], properties: { datetime: null, start_datetime: '2026-10-16T00:00:00Z', end_datetime: '2026-10-31T23:59:59Z' }, assets: Object.fromEntries(['B04', 'B03', 'B02'].map(b => [b, { href: asset(b) }])) }] } })); }, render: async () => ({ png: Buffer.from('fixture-png'), width: 16, height: 16, render_bounds: [[-60, -3], [-59.999, -2.999]], bytes_read: 11 }) });
    app = await buildServer();
    for (const [id, set] of [[user, (h: any) => headers = h], [user2, (h: any) => headers2 = h]] as const) {
        const r = await app.inject({ method: 'POST', url: '/api/v1/auth/session', payload: { user_id: id } });
        expect(r.statusCode, r.body).toBe(200);
        set({ cookie: r.cookies.map(c => `${c.name}=${c.value}`).join('; '), 'x-csrf-token': r.json().csrf_token });
    }
});
afterAll(async () => { configureImageryForTests(); await app.close(); await owner.$disconnect(); });
it('validates before IO, isolates cache/PNG, preserves immutable references and evaluation state', async () => {
    expect((await app.inject({ method: 'POST', url: '/api/v1/imagery/search', payload: { geometry, datetime } })).statusCode).toBe(401);
    const bad = await post('/api/v1/imagery/search', { geometry, datetime: '2026-11-01T00:00:00Z/2026-01-01T00:00:00Z' });
    expect(bad.statusCode, bad.body).toBe(422);
    expect(calls).toBe(0);
    const huge = { type: 'Polygon', coordinates: [[[-60,-3],[-59,-3],[-59,-2],[-60,-2],[-60,-3]]] };
    expect((await post('/api/v1/imagery/search', { geometry: huge, datetime })).statusCode).toBe(422);
    expect(calls).toBe(0);
    const key = randomUUID();
    const result = await post('/api/v1/imagery/search', { geometry, datetime }, headers, key);
    expect(result.statusCode, result.body).toBe(200);
    const query = result.json();
    expect(query.scenes[0].cloud_cover).toBeNull();
    expect(calls).toBe(1);
    const replay = await post('/api/v1/imagery/search', { geometry, datetime }, headers, key);
    expect(replay.json()).toEqual(query);
    expect(calls).toBe(1);
    const conflict = await post('/api/v1/imagery/search', { geometry, datetime: '2025-01-01T00:00:00Z/2026-11-01T00:00:00Z' }, headers, key);
    expect(conflict.statusCode).toBe(409);
    const cached = await post('/api/v1/imagery/search', { geometry, datetime });
    expect(cached.json().cached).toBe(true);
    expect(cached.json().queried_at).toBe(query.queried_at);
    const png = await app.inject({ url: query.scenes[0].render_url, headers });
    expect(png.statusCode, png.body).toBe(200);
    expect(png.headers['cache-control']).toBe('private, no-store');
    expect((await app.inject({ url: query.scenes[0].render_url, headers: headers2 })).statusCode).toBe(404);
    const plot = await owner.plot.create({ data: { organization_id: org, state: 'AM', municipality: 'Teste', declared_property: 'Sintética', geometry, geometry_hash: sha256Canonical(geometry), created_by_user_id: user, geometry_version: 1, geometry_date: new Date(), area_ha: 1, data_provenance: { label: 'SIMULADA' } } });
    const counts = await Promise.all([owner.check.count(), owner.sourceQuery.count(), owner.custodyEvent.count({ where: { stream_id: plot.id } })]);
    const linkKey = randomUUID();
    const link = await post(`/api/v1/plots/${plot.id}/imagery-references`, { query_id: query.query_id, scene_key: query.scenes[0].scene_key, geometry_version: 1 }, headers, linkKey);
    expect(link.statusCode, link.body).toBe(200);
    expect(link.json().references).toHaveLength(1);
    expect((await post(`/api/v1/plots/${plot.id}/imagery-references`, { query_id: query.query_id, scene_key: query.scenes[0].scene_key, geometry_version: 2 })).statusCode).toBe(409);
    expect((await post(`/api/v1/plots/${plot.id}/imagery-references`, { query_id: query.query_id, scene_key: query.scenes[0].scene_key, geometry_version: 1 }, headers2)).statusCode).toBe(404);
    const otherSearch = await post('/api/v1/imagery/search', { geometry, datetime }, headers2);
    expect(otherSearch.statusCode).toBe(200);
    expect(otherSearch.json().query_id).not.toBe(query.query_id);
    expect(calls).toBe(2);
    await owner.membership.create({ data: { user_id: user, organization_id: other, role: 'OPERATOR' } });
    await owner.user.update({ where: { id: user }, data: { organization_id: other } });
    expect((await post('/api/v1/imagery/search', { geometry, datetime }, headers, key)).statusCode).toBe(409);
    expect((await post(`/api/v1/plots/${plot.id}/imagery-references`, { query_id: query.query_id, scene_key: query.scenes[0].scene_key, geometry_version: 1 }, headers, linkKey)).statusCode).toBe(404);
    await owner.user.update({ where: { id: user }, data: { organization_id: org } });
    await owner.plot.update({ where: { id: plot.id }, data: { geometry_hash: 'b'.repeat(64), geometry_version: 2 } });
    const oldReference = await app.inject({ url: `/api/v1/plots/${plot.id}/imagery-references`, headers });
    expect(oldReference.json().references[0].is_current).toBe(false);
    expect((await post(`/api/v1/plots/${plot.id}/imagery-references`, { query_id: query.query_id, scene_key: query.scenes[0].scene_key, geometry_version: 2 })).statusCode).toBe(409);
    await owner.plot.update({ where: { id: plot.id }, data: { geometry_hash: sha256Canonical(geometry), geometry_version: 1 } });
    expect(await Promise.all([owner.check.count(), owner.sourceQuery.count(), owner.custodyEvent.count({ where: { stream_id: plot.id } })])).toEqual(counts);
    const ref = await owner.plotImageryReference.findFirstOrThrow({ where: { plot_id: plot.id } });
    expect(await owner.custodyEvent.count({ where: { stream_id: ref.id, type: 'PLOT_IMAGERY_LINKED' } })).toBe(1);
    const changedFilters = await post('/api/v1/imagery/search', { geometry, datetime: '2025-01-01T00:00:00Z/2026-11-01T00:00:00Z' });
    expect(changedFilters.json().query_id).not.toBe(query.query_id);
    expect(calls).toBe(3);
    now += 2 * 3600000;
    const expired = await post('/api/v1/imagery/search', { geometry, datetime });
    expect(expired.json().cached).toBe(false);
    expect(expired.json().query_id).not.toBe(query.query_id);
    expect(calls).toBe(4);
    const cursor = sha256Canonical(randomUUID());
    const cursorParent = await owner.imageryQuery.findUniqueOrThrow({ where: { id: query.query_id } });
    await owner.imageryQuery.create({ data: { ...cursorParent, id: randomUUID(), next_cursor: cursor, next_request: { url: 'https://data.inpe.br/bdc/stac/v1/search?page=2', method: 'GET' }, geometry: cursorParent.geometry as any, context_provenance: cursorParent.context_provenance as any, filters: cursorParent.filters as any, snapshot: cursorParent.snapshot as any } });
    const page = await post('/api/v1/imagery/search', { geometry, datetime, cursor });
    expect(page.statusCode, page.body).toBe(200);
    expect((await owner.imageryQuery.findUniqueOrThrow({ where: { id: page.json().query_id } })).page).toBe(2);
    expect((await post('/api/v1/imagery/search', { geometry, datetime: '2025-01-01T00:00:00Z/2026-11-01T00:00:00Z', cursor })).statusCode).toBe(422);
    expect((await post('/api/v1/imagery/search', { geometry, datetime, cursor }, headers2)).statusCode).toBe(422);
    const unknown = query.scenes[0].render_url.replace(query.scenes[0].scene_key, '0'.repeat(64));
    expect((await app.inject({ url: unknown, headers })).statusCode).toBe(404);
    // Fresh query IDs exercise cold cache and the shared render semaphore.
    const original = await owner.imageryQuery.findUniqueOrThrow({ where: { id: query.query_id } });
    const renderUrls: string[] = [];
    for (let i = 0; i < 3; i++) {
        const id = randomUUID();
        await owner.imageryQuery.create({ data: { ...original, id, next_cursor: null, next_request: undefined, geometry: original.geometry as any, context_provenance: original.context_provenance as any, filters: original.filters as any, snapshot: original.snapshot as any } });
        renderUrls.push(query.scenes[0].render_url.replace(query.query_id, id));
    }
    let release!: () => void;
    const gate = new Promise<void>(resolve => { release = resolve; });
    let started = 0;
    configureImageryForTests({ enabled: () => true, render: async () => { started++; await gate; return { png: Buffer.from('png'), width: 16, height: 16, render_bounds: [[-60,-3],[-59.999,-2.999]], bytes_read: 3 }; } });
    const first = app.inject({ url: renderUrls[0], headers });
    const second = app.inject({ url: renderUrls[1], headers });
    const firstPromise = Promise.resolve(first), secondPromise = Promise.resolve(second);
    for (let i = 0; i < 100 && started < 2; i++) await new Promise(resolve => setTimeout(resolve, 10));
    expect(started).toBe(2);
    expect((await app.inject({ url: renderUrls[2], headers })).statusCode).toBe(429);
    release();
    expect((await firstPromise).statusCode).toBe(200);
    expect((await secondPromise).statusCode).toBe(200);
    configureImageryForTests({ enabled: () => true, render: async () => { throw new Error('synthetic asset failure'); } });
    expect((await app.inject({ url: renderUrls[2], headers })).statusCode).toBe(503);
    configureImageryForTests({ enabled: () => true, now: () => now, search: async () => { throw new Error('provider unavailable'); } });
    const failedSearch = await post('/api/v1/imagery/search', { geometry, datetime: '2024-01-01T00:00:00Z/2026-11-01T00:00:00Z' });
    expect(failedSearch.statusCode).toBe(503);
    expect(await owner.imageryQuery.count({ where: { organization_id: org, status: 'INDISPONIVEL' } })).toBe(1);
    now += 8 * 86400000;
    active = false;
    configureImageryForTests({ enabled: () => active, now: () => now });
    const preserved = await app.inject({ url: `/api/v1/plots/${plot.id}/imagery-references`, headers });
    expect(preserved.statusCode, preserved.body).toBe(200);
    expect(preserved.json().references[0].scene.item_id).toBe('synthetic-scene');
    expect((await post('/api/v1/imagery/search', { geometry, datetime })).statusCode).toBe(503);
    expect((await app.inject({ url: query.scenes[0].render_url, headers })).statusCode).toBe(503);
});
