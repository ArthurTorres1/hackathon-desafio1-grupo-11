import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { PrismaClient } from '@prisma/client';
import { createHash, randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildServer } from '../../src/app.js';
import { prisma } from '../../src/db.js';

const owner = new PrismaClient({ datasources: { db: { url: process.env.TEST_DATABASE_URL! } } });
const organization = randomUUID(); const buyerOrganization = randomUUID();
const operator = randomUUID(); const buyer = randomUUID(); const unlinked = randomUUID();
const csrfQuerySecret = 'never-persist-this-csrf-secret';
let app: Awaited<ReturnType<typeof buildServer>>;
let storage: string;
type Session = { headers: { cookie: string; 'x-csrf-token': string }; token: string; csrf: string };

async function login(userId: string): Promise<Session> {
  const response = await app.inject({ method: 'POST', url: '/api/v1/auth/session', payload: { user_id: userId, roles: ['REGULATOR'], organization_id: buyerOrganization } });
  expect(response.statusCode, response.body).toBe(200);
  const token = response.cookies.find(cookie => cookie.name === 'foresttrace_session')!.value;
  const csrf = response.json().csrf_token;
  return { headers: { cookie: response.cookies.map(cookie => `${cookie.name}=${cookie.value}`).join('; '), 'x-csrf-token': csrf }, token, csrf };
}

const documentBody = { name: 'Somente demonstração', type: 'AUTHORIZATION', content_base64: Buffer.from('EVIDÊNCIA SIMULADA').toString('base64'), source: 'Teste sintético', data_provenance: 'SIMULADA', assessment_scope: 'DEMONSTRATIVO', visibility: 'PRIVATE' };
let operatorSession: Session; let buyerSession: Session;
let documentId: string;

beforeAll(async () => {
  storage = await mkdtemp(join(tmpdir(), 'foresttrace-auth-'));
  process.env.PRIVATE_STORAGE_DIR = storage;
  await owner.organization.createMany({ data: [organization, buyerOrganization].map(id => ({ id, name: 'Autorização sintética', role: 'OPERATOR', state: 'AM', municipality: 'Teste', data_provenance: { label: 'SIMULADA' } })) });
  await owner.user.createMany({ data: [
    { id: operator, name: 'Autora vinculada', organization_id: organization, roles: ['OPERATOR', 'AUDITOR'] },
    { id: buyer, name: 'Leitor vinculado', organization_id: buyerOrganization, roles: ['BUYER'] },
    { id: unlinked, name: 'Sem vínculo ativo', organization_id: organization, roles: ['OPERATOR', 'AUDITOR'] },
  ] });
  await owner.membership.createMany({ data: [
    { user_id: operator, organization_id: organization, role: 'OPERATOR' },
    { user_id: buyer, organization_id: buyerOrganization, role: 'BUYER' },
    // A membership from a different organization cannot elevate the active scope.
    { user_id: operator, organization_id: buyerOrganization, role: 'AUDITOR' },
  ] });
  app = await buildServer();
  operatorSession = await login(operator); buyerSession = await login(buyer);
});

afterAll(async () => {
  await app?.close();
  await Promise.all([owner.$disconnect(), prisma.$disconnect()]);
  // This directory is freshly generated by this suite and contains synthetic bytes only.
  if (storage) await rm(storage, { recursive: true, force: true });
});

describe.sequential('sessões, memberships e grants persistidos', () => {
  it('exige vínculo na organização e ignora privilégios enviados pelo cliente', async () => {
    const denied = await app.inject({ method: 'POST', url: '/api/v1/auth/session', payload: { user_id: unlinked, roles: ['OPERATOR'] } });
    expect(denied.statusCode).toBe(403);
    expect(denied.json().error.code).toBe('MEMBERSHIP_REQUIRED');
    expect(await owner.session.count({ where: { user_id: unlinked } })).toBe(0);
    const accepted = await app.inject({ method: 'POST', url: '/api/v1/auth/session', payload: { user_id: operator, roles: ['REGULATOR'] } });
    expect(accepted.json().user.roles).toEqual(['OPERATOR']);
    expect(accepted.json().user.organization.id).toBe(organization);
    const personas = (await app.inject({ url: '/api/v1/auth/personas' })).json().personas;
    expect(personas.some((persona: { id: string }) => persona.id === unlinked)).toBe(false);
    expect(personas.find((persona: { id: string }) => persona.id === operator).roles).toEqual(['OPERATOR']);
  });

  it('armazena somente hashes de sessão/CSRF e protege os cookies', async () => {
    const session = await owner.session.findUniqueOrThrow({ where: { token_hash: createHash('sha256').update(operatorSession.token).digest('hex') } });
    expect(session.csrf_hash).toBe(createHash('sha256').update(operatorSession.csrf).digest('hex'));
    expect(JSON.stringify(session)).not.toContain(operatorSession.token);
    expect(JSON.stringify(session)).not.toContain(operatorSession.csrf);
    const response = await app.inject({ method: 'POST', url: '/api/v1/auth/session', payload: { user_id: operator } });
    expect(response.cookies.find(cookie => cookie.name === 'foresttrace_session')).toMatchObject({ httpOnly: true, sameSite: 'Lax', path: '/' });
    expect(response.cookies.find(cookie => cookie.name === 'foresttrace_csrf')).toMatchObject({ sameSite: 'Lax', path: '/' });
  });

  it('nega escrita anônima, CSRF e origem inválidos, sem token no registro R20', async () => {
    const anonymous = await app.inject({ method: 'POST', url: '/api/v1/documents', payload: documentBody });
    expect(anonymous.statusCode).toBe(401);
    const response = await app.inject({ method: 'POST', url: `/api/v1/documents?token=${csrfQuerySecret}`, payload: documentBody, headers: { cookie: operatorSession.headers.cookie, 'x-csrf-token': csrfQuerySecret, authorization: `Bearer ${csrfQuerySecret}`, 'idempotency-key': randomUUID() } });
    expect(response.statusCode).toBe(403);
    const entries = await owner.accessLog.findMany({ where: { request_id: response.json().error.request_id } });
    expect(entries).toHaveLength(1);
    expect(entries[0]).toMatchObject({ reason: 'CSRF_INVALID', allowed: false, user_id: operator });
    expect(JSON.stringify(entries)).not.toContain(csrfQuerySecret);
    expect(JSON.stringify(entries)).not.toContain(operatorSession.token);
    expect(JSON.stringify(entries)).not.toContain(operatorSession.csrf);
    const origin = await app.inject({ method: 'POST', url: '/api/v1/auth/session', payload: { user_id: operator }, headers: { origin: 'https://example.invalid' } });
    expect(origin.statusCode).toBe(403);
  });

  it('preserva autoria autenticada e exige grant explícito para comprador de outra organização', async () => {
    const created = await app.inject({ method: 'POST', url: '/api/v1/documents', payload: { ...documentBody, created_by_user_id: buyer }, headers: { ...operatorSession.headers, 'idempotency-key': randomUUID() } });
    expect(created.statusCode, created.body).toBe(201);
    documentId = created.json().document.id;
    expect((await owner.document.findUniqueOrThrow({ where: { id: documentId } })).created_by_user_id).toBe(operator);
    const download = () => app.inject({ url: `/api/v1/documents/${documentId}/download`, headers: buyerSession.headers });
    expect((await download()).statusCode).toBe(404);
    const granted = await app.inject({ method: 'POST', url: `/api/v1/documents/${documentId}/grants`, payload: { organization_id: buyerOrganization }, headers: { ...operatorSession.headers, 'idempotency-key': randomUUID() } });
    expect(granted.statusCode, granted.body).toBe(201);
    expect((await download()).statusCode).toBe(200);
    const revoke = await app.inject({ method: 'DELETE', url: `/api/v1/documents/${documentId}/grants/${buyerOrganization}`, headers: { ...operatorSession.headers, 'idempotency-key': randomUUID() } });
    expect(revoke.statusCode).toBe(200);
    expect((await download()).statusCode).toBe(404);
  });

  it('revoga permissões na sessão existente e permite logout autenticado após revogação', async () => {
    await owner.membership.deleteMany({ where: { user_id: operator, organization_id: organization } });
    const denied = await app.inject({ url: `/api/v1/documents/${documentId}/download`, headers: operatorSession.headers });
    expect(denied.statusCode).toBe(403);
    expect(denied.json().error.code).toBe('MEMBERSHIP_REQUIRED');
    const missingCsrf = await app.inject({ method: 'DELETE', url: '/api/v1/auth/session', headers: { cookie: operatorSession.headers.cookie } });
    expect(missingCsrf.statusCode).toBe(403);
    const logout = await app.inject({ method: 'DELETE', url: '/api/v1/auth/session', headers: operatorSession.headers });
    expect(logout.statusCode).toBe(200);
    const replay = await app.inject({ url: '/api/v1/dashboard', headers: operatorSession.headers });
    expect(replay.statusCode).toBe(401);
  });

  it('sessão expirada não autoriza mesmo com membership válido', async () => {
    await owner.session.updateMany({ where: { token_hash: createHash('sha256').update(buyerSession.token).digest('hex') }, data: { expires_at: new Date(0) } });
    const response = await app.inject({ url: `/api/v1/documents/${documentId}/download`, headers: buyerSession.headers });
    expect(response.statusCode).toBe(401);
    expect(response.json().error.code).toBe('SESSION_INVALID');
  });
});
